#[cfg(test)]
mod tests {
    use super::*;

    // 2G, so the vector is independent of the generator constants.
    const X: [u8; 48] = [
        0x08, 0xd9, 0x99, 0x05, 0x7b, 0xa3, 0xd2, 0xd9, 0x69, 0x26, 0x00, 0x45, 0xc5, 0x5b, 0x97, 0xf0,
        0x89, 0x02, 0x59, 0x59, 0xa6, 0xf4, 0x34, 0xd6, 0x51, 0xd2, 0x07, 0xd1, 0x9f, 0xb9, 0x6e, 0x9e,
        0x4f, 0xe0, 0xe8, 0x6e, 0xbe, 0x0e, 0x64, 0xf8, 0x5b, 0x96, 0xa9, 0xc7, 0x52, 0x95, 0xdf, 0x61,
    ];
    const Y: [u8; 48] = [
        0x8e, 0x80, 0xf1, 0xfa, 0x5b, 0x1b, 0x3c, 0xed, 0xb7, 0xbf, 0xe8, 0xdf, 0xfd, 0x6d, 0xba, 0x74,
        0xb2, 0x75, 0xd8, 0x75, 0xbc, 0x6c, 0xc4, 0x3e, 0x90, 0x4e, 0x50, 0x5f, 0x25, 0x6a, 0xb4, 0x25,
        0x5f, 0xfd, 0x43, 0xe9, 0x4d, 0x39, 0xe2, 0x2d, 0x61, 0x50, 0x1e, 0x70, 0x0a, 0x94, 0x0e, 0x80,
    ];

    #[test]
    fn compressed_roundtrip() {
        let pk = PublicKey::from_xy(&X, &Y);
        let enc = pk.to_sec1_compressed();
        assert_eq!(enc[0], 0x02 | (Y[Y.len() - 1] & 1));
        assert_eq!(PublicKey::from_sec1_compressed(&enc), Ok(pk));
    }

    #[test]
    fn compressed_other_root() {
        let mut enc = PublicKey::from_xy(&X, &Y).to_sec1_compressed();
        enc[0] ^= 1;
        let other = PublicKey::from_sec1_compressed(&enc).unwrap();
        assert_eq!(other.x(), &X);
        assert_ne!(other.y(), &Y);
        assert_eq!(other.to_sec1_compressed(), enc);
    }

    #[test]
    fn compressed_rejects_invalid() {
        let mut enc = PublicKey::from_xy(&X, &Y).to_sec1_compressed();
        enc[0] = 0x04;
        assert!(PublicKey::from_sec1_compressed(&enc).is_err());

        // x = 1 gives a non-residue on both curves.
        let mut enc = [0u8; FIELD_SIZE + 1];
        enc[0] = 0x02;
        enc[FIELD_SIZE] = 1;
        assert!(PublicKey::from_sec1_compressed(&enc).is_err());

        // x = p is out of range.
        enc[1..].copy_from_slice(&PRIME);
        assert!(PublicKey::from_sec1_compressed(&enc).is_err());
    }
}
