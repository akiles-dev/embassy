#[cfg(test)]
mod tests {
    use super::*;

    // 2G, so the vector is independent of the generator constants.
    const X: [u8; 32] = [
        0x7c, 0xf2, 0x7b, 0x18, 0x8d, 0x03, 0x4f, 0x7e, 0x8a, 0x52, 0x38, 0x03, 0x04, 0xb5, 0x1a, 0xc3,
        0xc0, 0x89, 0x69, 0xe2, 0x77, 0xf2, 0x1b, 0x35, 0xa6, 0x0b, 0x48, 0xfc, 0x47, 0x66, 0x99, 0x78,
    ];
    const Y: [u8; 32] = [
        0x07, 0x77, 0x55, 0x10, 0xdb, 0x8e, 0xd0, 0x40, 0x29, 0x3d, 0x9a, 0xc6, 0x9f, 0x74, 0x30, 0xdb,
        0xba, 0x7d, 0xad, 0xe6, 0x3c, 0xe9, 0x82, 0x29, 0x9e, 0x04, 0xb7, 0x9d, 0x22, 0x78, 0x73, 0xd1,
    ];

    #[test]
    fn compressed_roundtrip() {
        let pk = PublicKey::from_xy(&X, &Y);
        let enc = pk.to_sec1_compressed();
        assert_eq!(enc[0], 0x02 | (Y[Y.len() - 1] & 1));
        assert_eq!(PublicKey::from_sec1_compressed(&enc), Ok(pk));
    }

    #[test]
    fn compressed_other_root() {
        let mut enc = PublicKey::from_xy(&X, &Y).to_sec1_compressed();
        enc[0] ^= 1;
        let other = PublicKey::from_sec1_compressed(&enc).unwrap();
        assert_eq!(other.x(), &X);
        assert_ne!(other.y(), &Y);
        assert_eq!(other.to_sec1_compressed(), enc);
    }

    #[test]
    fn compressed_rejects_invalid() {
        let mut enc = PublicKey::from_xy(&X, &Y).to_sec1_compressed();
        enc[0] = 0x04;
        assert!(PublicKey::from_sec1_compressed(&enc).is_err());

        // x = 1 gives a non-residue on both curves.
        let mut enc = [0u8; FIELD_SIZE + 1];
        enc[0] = 0x02;
        enc[FIELD_SIZE] = 1;
        assert!(PublicKey::from_sec1_compressed(&enc).is_err());

        // x = p is out of range.
        enc[1..].copy_from_slice(&PRIME);
        assert!(PublicKey::from_sec1_compressed(&enc).is_err());
    }
}
